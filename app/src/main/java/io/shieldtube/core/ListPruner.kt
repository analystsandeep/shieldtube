package io.shieldtube.core

/**
 * Runtime mirror of scripts/prune_lists.py for opportunistic list updates.
 * Updates are English/generic only and are always parsed with trusted=false;
 * bundled, checksum-verified lists remain the offline, trusted baseline.
 */
object ListPruner {
    private val KEEP = Regex(
        "(?i)(youtube|youtu\\.be|googlevideo|ytimg|doubleclick|googlesyndication|" +
            "googleadservices|adservice|pagead|advert|[-_./]ads?[-_./]|/ads?/|" +
            "analytics|tracker|tracking|pixel|beacon|sponsor|promoted|playerAds|" +
            "adPlacements|adSlots|gpt\\.js|pre-?roll|mid-?roll|ad-break|adContainer|" +
            "ytp-ad|masthead-ad|display-ad|promoted-sparkles|\\+js\\()"
    )

    private val HEADER =
        "! ShieldTube runtime update — English + generic rules only.\n" +
            "! Generated by core/ListPruner.kt. Parsed with trusted=false.\n"

    fun prune(text: String): List<String> {
        val seen = LinkedHashSet<String>()
        for (raw in text.lineSequence()) {
            val line = raw.trim()
            if (line.isEmpty() || line.startsWith("!") || line.startsWith("#") ||
                line.startsWith("[Adblock")
            ) continue
            if (line.length > 600) continue
            if (line.any { it.code > 127 }) continue
            if (!KEEP.containsMatchIn(line)) continue
            seen.add(line)
        }
        return seen.toList()
    }

    fun combine(texts: List<String>): String {
        val seen = LinkedHashSet<String>()
        for (text in texts) {
            for (line in prune(text)) seen.add(line)
        }
        return HEADER + seen.joinToString("\n") + "\n"
    }
}
