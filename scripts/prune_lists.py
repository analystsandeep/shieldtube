"""Deterministic filter-list pruner + checksum manifest generator.

Language policy (lead decision 2026-11-11): English + language-agnostic rules
only. Rules containing non-ASCII text are regional/localised rules and are
dropped. Regional source files are never fetched in the first place.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

# Anything that can plausibly affect ads on the YouTube TV web app.
KEEP = re.compile(
    r"(?i)(youtube|youtu\.be|googlevideo|ytimg|doubleclick|googlesyndication|"
    r"googleadservices|adservice|pagead|advert|[-_./]ads?[-_./]|/ads?/|"
    r"analytics|tracker|tracking|pixel|beacon|sponsor|promoted|playerAds|"
    r"adPlacements|adSlots|gpt\.js|pre-?roll|mid-?roll|ad-break|adContainer|"
    r"ytp-ad|masthead-ad|display-ad|promoted-sparkles|\+js\()"
)
YOUTUBE = re.compile(r"(?i)(youtube|youtu\.be|googlevideo|ytimg)")

GROUPS: dict[str, list[str]] = {
    "brave-specific.txt": ["brave-specific.txt"],
    "brave-unbreak.txt": ["brave-unbreak.txt"],
    "ubo-filters.txt": ["ubo-filters.txt", "ubo-filters-2026.txt", "ubo-quick-fixes.txt"],
    "ubo-unbreak.txt": ["ubo-unbreak.txt"],
    "easylist-core.txt": [
        "easylist-adservers.txt",
        "easylist-general-block.txt",
        "easylist-specific-block.txt",
        "easylist-thirdparty.txt",
        "easylist-allowlist.txt",
    ],
    "easyprivacy-core.txt": [
        "easyprivacy-general.txt",
        "easyprivacy-thirdparty.txt",
        "easyprivacy-specific-ubo.txt",
        "easyprivacy-allowlist.txt",
    ],
}

MAX_TOTAL_BYTES = 2 * 1024 * 1024  # brief: under 2 MB total after pruning
HEADER = "! ShieldTube pruned build — English + generic rules only.\n! Generated by scripts/prune_lists.py. Do not edit.\n"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def prune(text: str) -> list[str]:
    out: list[str] = []
    seen: set[str] = set()
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith(("!", "#", "[Adblock")):
            continue
        if len(line) > 600:  # pathological/obfuscated regional rules
            continue
        if any(ord(c) > 127 for c in line):  # non-English rule text
            continue
        if not KEEP.search(line):
            continue
        if line in seen:
            continue
        seen.add(line)
        out.append(line)
    return out


def resource_references(lines: list[str]) -> set[str]:
    refs: set[str] = set()
    for line in lines:
        for m in re.finditer(r"\+js\(\s*([^,\s\)]+)", line):
            refs.add(m.group(1).strip().strip("'\""))
        for m in re.finditer(r"redirect(?:-rule)?=([^,\s]+)", line):
            refs.add(m.group(1).strip())
    return refs


def prune_resources(data: list[dict], refs: set[str]) -> list[dict]:
    by_name = {r["name"]: r for r in data}

    def aliases(r: dict) -> set[str]:
        names = {r["name"], *r.get("aliases", [])}
        return {n for n in list(names) for n in (n, n.removesuffix(".js"))}

    selected: set[str] = set()
    queue: list[str] = []
    for r in data:
        if aliases(r) & refs or any(x in refs for x in aliases(r)):
            selected.add(r["name"])
            queue.append(r["name"])
    # Resolve dependencies transitively (canonical names only).
    while queue:
        name = queue.pop()
        r = by_name.get(name)
        if r is None:
            continue
        for dep in r.get("dependencies", []):
            dep = dep if dep in by_name else dep + ".js"
            if dep in by_name and dep not in selected:
                selected.add(dep)
                queue.append(dep)
    return [r for r in data if r["name"] in selected]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--legal", required=True, type=Path)
    ap.add_argument("--previous", required=True, type=Path)
    args = ap.parse_args()

    sources = json.loads((args.raw / "sources.json").read_text())
    args.out.mkdir(parents=True, exist_ok=True)
    args.legal.mkdir(parents=True, exist_ok=True)

    previous: dict[str, str] = {}
    if args.previous.is_file():
        try:
            for entry in json.loads(args.previous.read_text())["inputs"]:
                previous[entry["file"]] = entry["upstreamSha256"]
        except (KeyError, json.JSONDecodeError):
            print("[prune] previous SOURCES.json unreadable; ignoring", file=sys.stderr)

    raw_bytes: dict[str, bytes] = {}
    for entry in sources:
        name = entry["file"]
        data = (args.raw / name).read_bytes()
        digest = sha256(data)
        if name in previous and previous[name] != digest:
            print(
                f"[prune] FATAL: {name} changed at pinned SHA {entry['sha']} "
                f"({digest} != {previous[name]})",
                file=sys.stderr,
            )
            return 2
        raw_bytes[name] = data
        entry["upstreamSha256"] = digest
        print(f"[prune] {name:32s} {len(data):8d} bytes  {digest[:12]}…")

    outputs: dict[str, bytes] = {}
    all_kept: list[str] = []
    for out_name, inputs in GROUPS.items():
        lines: list[str] = []
        for src in inputs:
            lines.extend(prune(raw_bytes[src].decode("utf-8", "replace")))
        # Deterministic dedup, original rule order preserved.
        seen: set[str] = set()
        lines = [x for x in lines if not (x in seen or seen.add(x))]
        all_kept.extend(lines)
        outputs[out_name] = (HEADER + "\n".join(lines) + "\n").encode()
        print(f"[prune] -> {out_name:32s} {len(lines):6d} rules, {len(outputs[out_name]):8d} bytes")

    resources = json.loads(raw_bytes["resources.json"].decode())
    refs = resource_references(all_kept)
    # Brave's dist/resources.json holds only Brave-specific resources. The
    # pruned uBO lists reference many uBO scriptlets that are NOT in that set.
    # Keep the whole (small) resource library so any of those that do exist can
    # be injected, and record the unresolved names instead of silently dropping
    # them. Our own document-start shim implements the load-bearing
    # json-prune / trusted-replace-fetch-response behaviour in JS.
    present: set[str] = set()
    for r in resources:
        for n in [r["name"], *r.get("aliases", [])]:
            present.add(n)
            present.add(n.removesuffix(".js"))
    unresolved = sorted(refs - present)
    kept_resources = sorted(resources, key=lambda r: r["name"])
    outputs["resources.json"] = (
        json.dumps(kept_resources, sort_keys=True, separators=(",", ":")) + "\n"
    ).encode()
    print(
        f"[prune] -> resources.json              {len(kept_resources):6d} resources, "
        f"{len(outputs['resources.json'])} bytes, {len(unresolved)} unresolved uBO scriptlet refs"
    )

    # GPLv3 source availability: ship the upstream scriptlets source verbatim.
    legal_bytes = raw_bytes["ubo-scriptlets.js"]
    (args.legal / "ubo-scriptlets.js").write_bytes(legal_bytes)

    total = sum(len(v) for v in outputs.values()) + len(legal_bytes)
    if total > MAX_TOTAL_BYTES:
        print(f"[prune] FATAL: {total} bytes exceeds 2 MB cap", file=sys.stderr)
        return 3

    for name, data in outputs.items():
        (args.out / name).write_bytes(data)

    checksums = "".join(
        f"{sha256(data)}  {name}\n" for name, data in sorted(outputs.items())
    )
    checksums += f"{sha256(legal_bytes)}  ../legal/ubo-scriptlets.js\n"
    (args.out / "CHECKSUMS.sha256").write_text(checksums)

    manifest = {
        "schema": 1,
        "languages": ["en", "generic"],
        "totalBytes": total,
        "capBytes": MAX_TOTAL_BYTES,
        "unresolvedScriptletReferences": unresolved,
        "note": (
            "Brave dist/resources.json contains only Brave-specific resources; "
            "uBO scriptlet names referenced by the vendored lists are resolved "
            "by the app's own document-start shim, not by adblock-rust."
        ),
        "inputs": sources,
        "outputs": [
            {"file": name, "sha256": sha256(data), "bytes": len(data)}
            for name, data in sorted(outputs.items())
        ],
        "legal": [
            {
                "file": "app/src/main/assets/legal/ubo-scriptlets.js",
                "sha256": sha256(legal_bytes),
                "bytes": len(legal_bytes),
            }
        ],
    }
    (args.out / "SOURCES.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    print(f"[prune] total vendored payload: {total} bytes ({total / 1024 / 1024:.2f} MiB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
